    VEHICLE_NUMBER      VARCHAR2(32) DEFAULT 'AP-31-EV-8840',
    DRIVER_NAME         VARCHAR2(64) DEFAULT 'Suresh Kumar',
    DRIVER_CONTACT      VARCHAR2(32) DEFAULT '+91 98480 22331',
